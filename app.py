def normalize(text):
    text = (text or "").lower().strip()
    text = re.sub(r"(.)\1{2,}", r"\1", text)

    for old, new in NORMALIZATION_MAP.items():
        text = text.replace(old, new)

    return text


def fix_spelling(text):
    low = (text or "").lower()

    for wrong, right in SPELL_FIX.items():
        if wrong in low:
            return wrong, right

    return None, None


def is_gibberish(question, normalized):
    clean = re.sub(
        r"[^a-zA-Z0-9\u0980-\u09FF ]",
        "",
        question.lower()
    ).strip()

    if len(clean) < 2:
        return False

    known = [
        "kemon", "korcho", "kothay", "khaicho",
        "khida", "jaba", "valo", "sundor",
        "somossa", "biye", "ghum", "siyam",
        "monkharap", "dhonnobad", "boss", "tumi",
        "assalam", "salam", "hello", "bye",
    ]

    if any(word in normalized for word in known):
        return False

    vowels = "aeiouঅআইঈউঊএঐওঔ"

    if len(clean) >= 4 and not any(char in vowels for char in clean):
        return True

    return clean.replace(" ", "") in {
        "asdf",
        "asdfg",
        "asdfgh",
        "qwerty",
        "zxcv",
        "zxcvbn",
        "ajsk",
        "ajskd",
        "hjsd",
        "dfghjk",
    }


