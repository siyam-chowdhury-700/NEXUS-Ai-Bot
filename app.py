def handle_message(question, image_file=None):
    question = (question or "").strip()
    has_image = image_file is not None and bool(image_file.filename)

    if not question and not has_image:
        return "কোনো বার্তা পাওয়া যায়নি।", False

    # End all sessions politely after the configured local threshold or quota block.
    if api_budget_closed():
        return farewell_message(), True

    normalized = normalize(question)
    wrong, right = fix_spelling(question)

    note = (
        f"\n\n(তুমি '{wrong}' লিখেছো, সঠিক বানান হলো '{right}'।)"
        if wrong else ""
    )

    day_key = get_day_key()

    if session.get("last_intro_day") != day_key:
        session["last_intro_day"] = day_key

        intro = (
            "আসসালামু আলাইকুম। আমি NEXUS AI, Siyam Chowdhury-এর "
            "Personal AI Assistant। Boss-এর হয়ে আপনাকে কীভাবে "
            "সাহায্য করতে পারি?\n\n"
        )
    else:
        intro = ""

    if not has_image and is_gibberish(question, normalized):
        answer, close = (
            "দুঃখিত, আমি এইটা বুঝতে পারিনি। একটু বুঝিয়ে লিখবে?",
            False,
        )

    elif is_boss_call_check(normalized):
        if not session.get("boss_called"):
            session["boss_called"] = True
            answer, close = (
                "আমি Boss-কে জানাচ্ছি। উনি সময় পেলে কথা বলবেন ইনশাআল্লাহ।",
                False,
            )
        else:
            answer, close = (
                "Boss এখন ব্যস্ত আছেন। পরে কথা বলবেন ইনশাআল্লাহ।",
                False,
            )

    elif contains_word(normalized, [
        "tumi ke",
        "tomar nam",
        "porichoy",
        "who are you",
        "tomar malik",
        "tomake ke",
        "ke bana",
        "boss er nam",
    ]):
        answer = (
            "আমি NEXUS AI, Siyam Chowdhury-এর Personal AI Assistant। "
            "NEXUS-এর প্রতিষ্ঠাতা Siyam Chowdhury।"
        )
        close = False

    elif "assalam" in normalized or "salam" in normalized:
        answer, close = (
            "ওয়ালাইকুম আসসালাম। আমি NEXUS AI। কীভাবে সাহায্য করতে পারি?",
            False,
        )

    elif contains_word(normalized, ["hi", "hello", "hey"]):
        answer, close = (
            "আসসালামু আলাইকুম। আমি NEXUS AI। কীভাবে সাহায্য করতে পারি?",
            False,
        )

    elif any(word in normalized for word in [
        "delete", "ডিলিট", "mucho", "mucha", "মুছ"
    ]):
        answer, close = "আমি নিজে কোনো মেসেজ ডিলিট করতে পারি না।", False

    elif any(word in normalized for word in [
        "lukao", "lukaba", "hide", "লুকাও", "লুকাব"
    ]):
        answer, close = (
            "আমি অন্য ব্যবহারকারীর ব্যক্তিগত কথোপকথন প্রকাশ করি না।",
            False,
        )

    elif "kemon" in normalized:
        answer, close = "আলহামদুলিল্লাহ ভালো আছি। তুমি কেমন আছো?", False

    elif "kalke" in normalized and "jaba" in normalized:
        answer, close = "ইনশাআল্লাহ যাবো।", False

    elif "jaba" in normalized:
        answer, close = "ইনশাআল্লহ" 